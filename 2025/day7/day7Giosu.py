def part2(rows):
    splits = 0
    width = len(rows[0])
    counts = [[0 for _ in range(len(rows[0]))] for _ in range(len(rows))]

    for row in range(len(rows)):
        for pos in range(len(rows[row])):
            # manage the start
            if rows[row][pos] == 'S':
                selRow = rows[row + 1]
                newRow = selRow[:pos] + '|' + selRow[pos + 1:]
                counts[row + 1][pos] = 1
                rows[row + 1] = newRow
                continue
            
            # flow
            if row > 0 and rows[row - 1][pos] == '|':
                prev_count = counts[row - 1][pos]
                curr_char = rows[row][pos]

                if curr_char == '.' or curr_char == '|':
                    # normal flow without splits
                    counts[row][pos] += prev_count
                    rows[row] = rows[row][:pos] + '|' + rows[row][pos+1:]

                elif curr_char == '^':
                    # Split and sum from prev
                    # LX
                    if pos - 1 >= 0:
                        counts[row][pos - 1] += prev_count
                        rows[row] = rows[row][:pos - 1] + '|' + rows[row][pos:]
                    # RX
                    if pos + 1 < width:
                        counts[row][pos + 1] += prev_count
                        rows[row] = rows[row][:pos + 1] + '|' + rows[row][pos + 2:]
    
    splits = 0
    for x in counts[len(counts) - 1]:
        splits += x

    print("Result:", splits)

