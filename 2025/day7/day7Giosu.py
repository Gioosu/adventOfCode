def part1(rows):
    splits = 0

    for row in range(len(rows)):
        for pos in range(len(rows[row])):
            # manage the start
            if rows[row][pos] == 'S':
                selRow = rows[row + 1]
                newRow = selRow[:pos] + '|' + selRow[pos + 1:]
                rows[row + 1] = newRow
                continue
            
            if row > 0:
                # just flowing
                if rows[row][pos] == '.' and rows[row - 1][pos] == '|':
                    selRow = rows[row]
                    newRow = selRow[:pos] + '|' + selRow[pos + 1:]
                    rows[row] = newRow
                    continue

                # splitting
                if rows[row][pos] == '^' and rows[row - 1][pos] == '|':
                    splits += 1
                    selRow = rows[row]
                    newRow = selRow[:pos - 1] + '|' + selRow[pos] + '|' + selRow[pos + 2:]
                    rows[row] = newRow
                    continue
    
    printTree(rows)
    print(splits)

